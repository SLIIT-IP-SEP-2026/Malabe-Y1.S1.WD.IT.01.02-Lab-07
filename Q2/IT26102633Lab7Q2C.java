public class IT26102633Lab7Q2C {
    public static void main(String[] args) {
        // Outer loop starts from 5 down to 1
        for (int i = 5; i >= 1; i--) {
            // Inner loop prints the number 'i', repeated 'i' times
            for (int j = 1; j <= i; j++) {
                System.out.print(i);
            }
           
            System.out.println();
			
		}
		
	}
	
}